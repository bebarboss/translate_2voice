-- บัญชี เครดิต ความยินยอม และนักพากย์ ใน schema studio
-- แยกจาก public.profiles / public.ledger ที่ออกแบบไว้กับ Supabase Auth (id เป็น uuid)
-- แอปใช้ Google login และ id เป็นตัวอักษร โครงคอลัมน์ตรงกับ data/accounts.db
-- เวลาเป็น unix วินาที (double precision) เครดิตเป็นหน่วยย่อย (1 เครดิต = 100) เงินเป็นสตางค์
-- เชื่อมด้วย SUPABASE_DB_URL (ผู้ใช้ postgres) ไม่เปิดผ่าน PostgREST

create schema if not exists studio;

create table if not exists studio.users (
  id text primary key,
  email text unique not null,
  name text not null,
  pw_hash text not null default '',
  balance integer not null default 0,
  created_at double precision not null,
  credits integer not null default 0,
  admin integer not null default 0,
  full_name text not null default '',
  phone text not null default '',
  account_type text not null default '',
  company text not null default '',
  use_case text not null default '',
  profile_at double precision,
  deleted_at double precision,
  notify_email integer not null default 1
);

create table if not exists studio.sessions (
  token_hash text primary key,
  user_id text not null,
  expires_at double precision not null
);

create table if not exists studio.subscriptions (
  user_id text primary key,
  plan_id text not null,
  minutes_left integer not null,
  started_at double precision not null,
  expires_at double precision not null
);

create table if not exists studio.ledger (
  id bigint generated by default as identity primary key,
  user_id text not null,
  kind text not null,
  amount integer not null default 0,
  minutes integer not null default 0,
  ref text,
  note text not null default '',
  created_at double precision not null,
  credits integer not null default 0
);
create index if not exists ledger_user on studio.ledger (user_id, id);
-- One free-trial grant per user. Existing databases do not re-run this file;
-- apply backend/supabase/migrations/20261112000000_ledger_trial_once.sql by hand
-- (it skips the index when duplicate kind=trial rows exist and does not delete them).
create unique index if not exists ledger_trial_once on studio.ledger (user_id) where kind = 'trial';

create table if not exists studio.topups (
  id text primary key,
  user_id text not null,
  amount integer not null,
  provider text not null,
  status text not null,
  created_at double precision not null,
  paid_at double precision,
  credits integer not null default 0,
  plan_id text,
  note text not null default '',
  slip_hash text,
  ocr_text text,
  ocr_json text,
  ocr_amount integer
);

create table if not exists studio.cards (
  id text primary key,
  user_id text not null,
  provider text not null,
  ref text not null,
  brand text not null,
  last4 text not null,
  exp_month integer not null,
  exp_year integer not null,
  fingerprint text not null,
  created_at double precision not null
);
create index if not exists cards_user on studio.cards (user_id);

create table if not exists studio.slip_uses (
  hash text primary key,
  topup_id text not null,
  created_at double precision not null
);

create table if not exists studio.user_consents (
  id bigint generated by default as identity primary key,
  user_id text not null,
  kind text not null,
  version text not null,
  text_hash text not null default '',
  accepted integer not null,
  ip text not null default '',
  user_agent text not null default '',
  created_at double precision not null
);
create index if not exists user_consents_user on studio.user_consents (user_id, kind, id);

create table if not exists studio.actors (
  user_id text primary key,
  stage_name text not null,
  gender text not null default '',
  bio text not null default '',
  contact text not null default '',
  status text not null,
  note text not null default '',
  created_at double precision not null,
  reviewed_at double precision,
  reviewed_by text
);

create table if not exists studio.actor_consents (
  id bigint generated by default as identity primary key,
  user_id text not null,
  version text not null,
  text_hash text not null,
  ip text not null default '',
  user_agent text not null default '',
  accepted_at double precision not null,
  withdrawn_at double precision,
  items text not null default ''
);
create index if not exists actor_consents_user on studio.actor_consents (user_id, id);

create table if not exists studio.actor_voices (
  voice_id text primary key,
  user_id text not null,
  review text not null default 'pending',
  note text not null default '',
  created_at double precision not null,
  reviewed_at double precision,
  reviewed_by text
);
create index if not exists actor_voices_user on studio.actor_voices (user_id);

create table if not exists studio.voice_usage (
  job_id text not null,
  voice_id text not null,
  actor_id text not null,
  user_id text not null default '',
  job_name text not null default '',
  seconds double precision not null,
  lines integer not null,
  month text not null,
  created_at double precision not null,
  updated_at double precision not null,
  moods text not null default '{}',
  primary key (job_id, voice_id)
);
create index if not exists voice_usage_actor on studio.voice_usage (actor_id, month);

create table if not exists studio.actor_payouts (
  id bigint generated by default as identity primary key,
  actor_id text not null,
  month text not null,
  amount integer not null,
  note text not null default '',
  paid_by text not null,
  paid_at double precision not null,
  wht integer not null default 0,
  payee_name text not null default '',
  tax_id text not null default '',
  address text not null default '',
  tax_id_enc text,
  tax_id_hmac text
);
create index if not exists actor_payouts_actor on studio.actor_payouts (actor_id, month);
create index if not exists actor_payouts_tax_hmac on studio.actor_payouts (tax_id_hmac);

create table if not exists studio.actor_moods (
  voice_id text not null,
  mood text not null,
  review text not null default 'pending',
  note text not null default '',
  created_at double precision not null,
  reviewed_at double precision,
  reviewed_by text,
  primary key (voice_id, mood)
);

create table if not exists studio.actor_payment (
  user_id text primary key,
  payee_name text not null,
  tax_id text not null,
  address text not null,
  bank text not null,
  account_no text not null,
  account_name text not null,
  updated_at double precision not null,
  tax_id_enc text,
  tax_id_hmac text,
  account_no_enc text
);
create unique index if not exists actor_payment_tax_hmac_uniq
  on studio.actor_payment (tax_id_hmac)
  where tax_id_hmac is not null and tax_id_hmac <> '';
